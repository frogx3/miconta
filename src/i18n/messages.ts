/**
 * Diccionarios por locale. Una región solo declara lo que cambia respecto a su idioma
 * (p. ej. 'es-AR' sobrescribiría términos): el resto cae en el idioma y luego en es-MX.
 */
const dictionaries: Record<Locale, Partial<Dictionary>> = {
  'es-MX': es,
  es,
  en,
};

export function t(locale: Locale, key: MessageKey, params?: Record<string, string>): string {
  const language = locale.split('-')[0] as Locale;
  const template = dictionaries[locale]?.[key] ?? dictionaries[language]?.[key] ?? dictionaries[DEFAULT_LOCALE][key] ?? key;
  return params ? template.replace(/\{(\w+)\}/g, (_, name: string) => params[name] ?? `{${name}}`) : template;
}

/** Textos de un locale cuyas claves empiezan por alguno de los prefijos; para pasarlos al navegador. */
export function messagesFor(locale: Locale, prefixes: string[]): Record<string, string> {
  const keys = Object.keys(es) as MessageKey[];
  return Object.fromEntries(keys.filter((key) => prefixes.some((prefix) => key.startsWith(prefix))).map((key) => [key, t(locale, key)]));
}

/** Texto con singular/plural: usa la clave `<base>.one` cuando n es 1 y `<base>.other` en los demás casos. */
export function tn(locale: Locale, base: string, n: number, params: Record<string, string> = {}): string {
  return t(locale, `${base}.${n === 1 ? 'one' : 'other'}` as MessageKey, { n: String(n), ...params });
}
